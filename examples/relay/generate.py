def fillers(log: Log) -> None:
    rng = random.Random(7)
    n_ticket = 4000
    for i, name in enumerate(FILLER):
        t = name.lower().replace(" ", "-").replace("'", "")
        created = START + timedelta(days=rng.randrange(0, 120), hours=rng.randrange(0, 8))
        plan = rng.choice(("starter", "starter", "pro", "pro", "enterprise"))
        seats = rng.choice((5, 8, 12, 20, 35, 50, 80))
        region = rng.choice(REGIONS)
        account(log, t, name, created, plan, seats, region, csm="Sam Lee" if plan == "enterprise" else None)
        contact(log, t, f"C-{t}-1", rng.choice(("Ana", "Ben", "Chloe", "Diego", "Eva", "Femi", "Grace")) + " " + rng.choice(("Ruiz", "Kim", "Okafor", "Silva", "Novak")),
                rng.choice(("admin", "owner", "finance")), created + timedelta(hours=1))
        months = list(range(created.month + 1, 11))
        failed = rng.random() < 0.12 and months
        monthly(log, t, plan, seats, months, paid_day=rng.choice((1, 1, 2, 3)), skip=(months[-1],) if failed else ())
        if failed:
            m = months[-1]
            inv = f"INV-{t}-2026-{m:02d}"
            log.add(t, "invoice.issued", f"account:{t}", at(m, 1, 6), {"id": inv, "amount": float(PRICE[plan] * seats), "currency": "USD", "period": f"2026-{m:02d}",
                                                                      "prorated": False, "description": f"{plan.title()} plan, {seats} seats, {at(m, 1):%B %Y}"})
            log.add(t, "payment.failed", f"invoice:{inv}", at(m, 1, 7), {"reason": rng.choice(("card_declined", "card_expired", "insufficient_funds"))})
        if rng.random() < 0.15 and plan != "enterprise":
            new = "pro" if plan == "starter" else "enterprise"
            log.add(t, "subscription.changed", f"account:{t}", created + timedelta(days=rng.randrange(40, 90)), {"plan": new, "seats": seats, "previous_plan": plan})
        for app in rng.sample(APPS, rng.randrange(0, 3)):
            log.add(t, "integration.status_changed", f"account:{t}", created + timedelta(days=2), {"id": f"I-{t}-{app.lower()}", "app": app, "status": "connected", "error": None})
        incidents_for(log, t, region, created, rng)
        for _ in range(rng.randrange(0, 4)):
            n_ticket += 1
            opened = created + timedelta(days=rng.randrange(5, 150), hours=rng.randrange(0, 10))
            cat = rng.choice(CATEGORIES)
            title = {"billing": "Question about my invoice", "integrations": "Sync not updating", "workflows": "Workflow stuck in queue",
                     "access": "Cannot invite a teammate", "api": "Rate limit on the API"}[cat]
            ticket(log, t, f"T-{n_ticket}", title, rng.choice(("low", "normal", "normal", "high")), cat, opened,
                   [(opened + timedelta(hours=rng.randrange(2, 60)), "resolved", "Answered and closed.")])


def main() -> None:
    log = Log()
    planted(log)
    histories(log)
    fillers(log)
    n = log.write(Path(__file__).parent / "events.jsonl")
    print(f"{n} events, {len({e['tenant'] for e in log.events})} customers")


if __name__ == "__main__":
    main()
