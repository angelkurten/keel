class Log:
    def __init__(self) -> None:
        self.events: list[dict] = []

    def add(self, tenant: str, type_: str, subject: str, at: datetime, payload: dict) -> None:
        owner = {"account": "core", "contact": "core", "subscription": "billing", "invoice": "billing", "payment": "billing",
                 "refund": "billing", "ticket": "support", "incident": "platform", "integration": "integrations"}[type_.split(".")[0]]
        if at > TODAY:
            return
        self.events.append({"tenant": tenant, "type": type_, "subject": subject, "occurred_at": at.isoformat().replace("+00:00", "Z"),
                            "source": f"relay.{owner}", "payload": payload})

    def write(self, path: Path) -> int:
        self.events.sort(key=lambda e: (e["occurred_at"], e["tenant"], e["type"]))
        with path.open("w", encoding="utf-8") as fh:
            fh.write(f"# Relay, generated by generate.py (seeded): {len({e['tenant'] for e in self.events})} customers, today = {TODAY.isoformat()}\n")
            for n, e in enumerate(self.events, 1):
                fh.write(json.dumps({"id": f"relay-{n:05d}", **e}, separators=(",", ":")) + "\n")
        return len(self.events)


def at(month: int, day: int, hour: int = 9, minute: int = 0) -> datetime:
    return datetime(2026, month, day, hour, minute, tzinfo=UTC)


def account(log: Log, t: str, name: str, created: datetime, plan: str, seats: int, region: str, csm: str | None = None) -> None:
    log.add(t, "account.created", f"account:{t}", created, {"name": name, "region": region, "plan": plan, "seats": seats, "csm": csm})


def contact(log: Log, t: str, cid: str, name: str, role: str, when: datetime, language: str = "en") -> None:
    email = f"{name.split()[0].lower()}@{t}.example"
    log.add(t, "contact.added", f"account:{t}", when, {"id": cid, "name": name, "role": role, "email": email, "language": language})


def monthly(log: Log, t: str, plan: str, seats: int, months: list[int], paid_day: int = 1, skip: tuple[int, ...] = ()) -> None:
    for m in months:
        if m in skip:
            continue
        inv = f"INV-{t}-2026-{m:02d}"
        amount = PRICE[plan] * seats
        log.add(t, "invoice.issued", f"account:{t}", at(m, 1, 6), {"id": inv, "amount": float(amount), "currency": "USD", "period": f"2026-{m:02d}",
                                                                  "prorated": False, "description": f"{plan.title()} plan, {seats} seats, {at(m, 1):%B %Y}"})
        log.add(t, "invoice.paid", f"invoice:{inv}", at(m, paid_day, 7), {"amount": float(amount)})


def ticket(log: Log, t: str, tid: str, title: str, priority: str, category: str, opened: datetime, changes: list[tuple[datetime, str, str | None]]) -> None:
    log.add(t, "ticket.opened", f"account:{t}", opened, {"id": tid, "title": title, "priority": priority, "category": category})
    for when, status, note in changes:
        log.add(t, "ticket.status_changed", f"ticket:{tid}", when, {"status": status, "note": note})


