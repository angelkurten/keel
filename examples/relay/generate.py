def incidents_for(log: Log, t: str, region: str, created: datetime, rng: random.Random, always: bool = False) -> None:
    for iid, title, sev, reg, start, end, summary in INCIDENTS:
        if reg == region and start > created and (always or rng.random() < 0.6):
            log.add(t, "incident.affected", f"account:{t}", start, {"id": iid, "title": title, "severity": sev, "region": reg})
            log.add(t, "incident.resolved", f"incident:{iid}", end, {"summary": summary})


