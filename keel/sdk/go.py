"""Go template. Output imports the runtime module `github.com/angelkurten/keel/sdk/go` (package keel)."""

from __future__ import annotations

import json
from typing import Any

from keel.sdk.naming import identifier, pascal


class _Types:
    """Collects named struct and enum definitions; nested objects become `<Parent><Field>` structs."""

    def __init__(self) -> None:
        self.defs: list[str] = []

    def expr(self, schema: dict[str, Any], name: str) -> tuple[str, bool]:
        """(type expression, nullable)"""
        if "enum" in schema:
            rows = [[f"{name}{pascal(identifier(str(v)))}", name, f"= {json.dumps(v)}"] for v in schema["enum"]]
            self.defs.append(f"type {name} string\n\nconst (\n" + "\n".join(_align(rows)) + "\n)\n")
            return name, False
        t = schema.get("type")
        if t is None:
            return "any", False
        types = [x for x in (t if isinstance(t, list) else [t]) if x != "null"]
        nullable = isinstance(t, list) and "null" in t
        ty = types[0] if types else "null"
        if ty == "string":
            return "string", nullable
        if ty == "integer":
            return "int64", nullable
        if ty == "number":
            return "float64", nullable
        if ty == "boolean":
            return "bool", nullable
        if ty == "array":
            inner, _ = self.expr(schema.get("items") or {}, name + "Item")
            return "[]" + inner, nullable
        if ty == "object":
            return self.struct(schema, name), nullable
        return "any", nullable

    def struct(self, schema: dict[str, Any], name: str) -> str:
        props = schema.get("properties") or {}
        if not props:
            return "map[string]any"
        required = set(schema.get("required") or [])
        rows = []
        for k, v in props.items():
            expr, nullable = self.expr(v, name + pascal(k))
            optional = k not in required
            if nullable and not expr.startswith("[]") and expr != "any":
                expr = "*" + expr
            rows.append([pascal(k), expr, f'`json:"{k}{",omitempty" if optional else ""}"`'])
        self.defs.append(f"type {name} struct {{\n" + "\n".join(_align(rows)) + "\n}\n")
        return name


def render(doc: dict[str, Any], **options: Any) -> str:
    name, kinds, relations, events = doc["cartridge"], list(doc["entities"]), list(doc["relations"]), doc["events"]
    package = options.get("package") or f"keel{name}".replace("-", "").replace("_", "")
    types = _Types()
    payload_types = {t: types.expr(spec["payload"], pascal(t) + "Payload")[0] for t, spec in events.items()}
    lines = [
        f"// Code generated by keel-context {doc['keel']} from cartridge {name}" + (f" {doc['version']}" if doc.get("version") else "") + ". DO NOT EDIT.",
        f"// Regenerate: keel sdk go <path to {name}> -o <this file> --package {package}",
        f"package {package}",
        "",
        "import (",
        '\t"time"',
        "",
        '\tkeel "github.com/angelkurten/keel/sdk/go"',
        ")",
        "",
        f"const Cartridge = {json.dumps(name)}",
        "",
        "var (",
        f"\tKinds     = {_slice(kinds)}",
        f"\tRelations = {_slice(relations)}",
        f"\tAgents    = {_slice(list(doc['agents']))}",
        '\tScopes    = []string{"global", "tenant", "task", "agent"}',
        ")",
        "",
        "// RulesJSON is the cartridge's semantic layer, verbatim; json.Unmarshal it when an agent needs a definition.",
        "const RulesJSON = `" + json.dumps(doc["rules"], ensure_ascii=False).replace("`", "'") + "`",
        "",
        "// Subject is a '<kind>:<id>' key.",
        "type Subject string",
        "",
        *[f"func Subject{pascal(k)}(id string) Subject {{ return Subject({json.dumps(k + ':')} + id) }}\n" for k in kinds],
        "// Event payloads (cartridge.yaml `payload:`; extra fields are allowed by the server)",
        "",
        *types.defs,
        "// One constructor per cataloged event: a valid envelope, typed by subject kind and payload.",
        "",
    ]
    for etype in events:
        lines += [
            f"func Emit{pascal(etype)}(tenant string, subject Subject, occurredAt time.Time, source string, payload {payload_types[etype]}) keel.Envelope {{",
            f"\treturn keel.NewEnvelope(tenant, {json.dumps(etype)}, string(subject), occurredAt, source, payload)",
            "}",
            "",
        ]
    lines += [
        "// NewClient binds the five tools to one tenant (and agent) at BaseURL.",
        "func NewClient(o keel.Options) *keel.Client { return keel.NewClient(o) }",
        "",
    ]
    return "\n".join(lines)


def _align(rows: list[list[str]]) -> list[str]:
    """Pad every column but the last to its block width, the way gofmt does."""
    widths = [max(len(r[i]) for r in rows) for i in range(len(rows[0]) - 1)]
    return ["\t" + " ".join([r[i].ljust(widths[i]) for i in range(len(widths))] + [r[-1]]) for r in rows]


def _slice(items: list[str]) -> str:
    return "[]string{" + ", ".join(json.dumps(i) for i in items) + "}"
