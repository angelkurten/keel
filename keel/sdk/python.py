"""Python template. Output imports the runtime `keel.client` and the envelope from `keel-context` itself."""

from __future__ import annotations

import json
from typing import Any

from keel.sdk.naming import pascal, snake


class _Types:
    """Collects the TypedDict definitions a payload needs (nested objects become named classes)."""

    def __init__(self) -> None:
        self.defs: list[str] = []

    def expr(self, schema: dict[str, Any], name: str) -> str:
        if "enum" in schema:
            values = [v for v in schema["enum"] if v is not None]
            expr = "Literal[" + ", ".join(json.dumps(v) if isinstance(v, str) else repr(v) for v in values) + "]"
            return expr + (" | None" if None in schema["enum"] else "")
        t = schema.get("type")
        if t is None:
            return "Any"
        types = t if isinstance(t, list) else [t]
        out = []
        for ty in types:
            if ty == "null":
                out.append("None")
            elif ty == "string":
                out.append("str")
            elif ty == "integer":
                out.append("int")
            elif ty == "number":
                out.append("float")
            elif ty == "boolean":
                out.append("bool")
            elif ty == "array":
                out.append(f"list[{self.expr(schema.get('items') or {}, name + 'Item')}]")
            elif ty == "object":
                out.append(self.typed_dict(schema, name))
        return " | ".join(out) or "Any"

    def typed_dict(self, schema: dict[str, Any], name: str) -> str:
        props = schema.get("properties") or {}
        if not props:
            return "dict[str, Any]"
        required = set(schema.get("required") or [])
        req = [(k, self.expr(v, name + pascal(k))) for k, v in props.items() if k in required]
        opt = [(k, self.expr(v, name + pascal(k))) for k, v in props.items() if k not in required]
        body_req = "\n".join(f"    {k}: {e}" for k, e in req) or "    pass"
        body_opt = "\n".join(f"    {k}: {e}" for k, e in opt)
        if opt:
            self.defs.append(f"class _{name}Required(TypedDict):\n{body_req}\n\n\nclass {name}(_{name}Required, total=False):\n{body_opt}\n")
        else:
            self.defs.append(f"class {name}(TypedDict):\n{body_req}\n")
        return name


def render(doc: dict[str, Any], **options: Any) -> str:
    name, kinds, relations, events = doc["cartridge"], list(doc["entities"]), list(doc["relations"]), doc["events"]
    types = _Types()
    payload_names = {t: types.expr(spec["payload"], pascal(t) + "Payload") for t, spec in events.items()}
    lines = [
        f"# Generated by keel-context from cartridge {name}" + (f" {doc['version']}" if doc.get("version") else "") + ". Do not edit.",
        f"# Regenerate: keel sdk python <path to {name}> -o <this file>",
        "from __future__ import annotations",
        "",
        "from datetime import datetime",
        "from typing import Any, Literal, TypedDict",
        "",
        "from keel.client import Client",
        "from keel.envelope import Event, parse_iso",
        "",
        f"CARTRIDGE = {json.dumps(name)}",
        f"KINDS = {tuple(kinds)!r}",
        f"RELATIONS = {tuple(relations)!r}",
        f"RULES: dict[str, Any] = {doc['rules']!r}",  # a Python literal: JSON's true/null are not Python
        f"AGENTS = {tuple(doc['agents'])!r}",
        'SCOPES = ("global", "tenant", "task", "agent")',
        "",
        "",
        "class subjects:",
        *[f"    @staticmethod\n    def {k}(id: str) -> str:\n        return f\"{k}:{{id}}\"\n" for k in kinds],
        "",
        "# Event payloads (cartridge.yaml `payload:`; extra keys are allowed by the server)",
        "",
        *types.defs,
        "",
        "def _envelope(type: str, tenant: str, subject: str, occurred_at: datetime | str, source: str, payload: Any, id: str | None, recorded_at: datetime | str | None) -> Event:",
        "    extra: dict[str, Any] = {}",
        "    if id:",
        '        extra["id"] = id',
        "    if recorded_at:",
        '        extra["recorded_at"] = parse_iso(recorded_at)',
        "    return Event(tenant=tenant, type=type, subject=subject, occurred_at=parse_iso(occurred_at), source=source, payload=dict(payload), **extra)",
        "",
        "",
        "class emit:",
        "    \"\"\"One constructor per cataloged event: a valid envelope, typed by payload.\"\"\"",
        "",
    ]
    for etype in events:
        lines += [
            "    @staticmethod",
            f"    def {snake(etype)}(tenant: str, subject: str, occurred_at: datetime | str, source: str, payload: {payload_names[etype]}, id: str | None = None, recorded_at: datetime | str | None = None) -> Event:",
            f"        return _envelope({json.dumps(etype)}, tenant, subject, occurred_at, source, payload, id, recorded_at)",
            "",
        ]
    lines += [
        "",
        "def client(base_url: str, tenant: str, secret: str | None = None, agent: str | None = None, timeout: float = 30.0, traceparent: str | None = None) -> Client:",
        "    \"\"\"The five tools over HTTP, bound to one tenant and agent. `traceparent` joins your trace to Keel's audit.\"\"\"",
        "    return Client(base_url, tenant, secret=secret, agent=agent, timeout=timeout, traceparent=traceparent)",
        "",
    ]
    return "\n".join(lines)
