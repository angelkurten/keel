"""PHP template (8.1+). Output uses the runtime `keel-context/sdk` (Composer, namespace Keel\\Sdk)."""

from __future__ import annotations

from typing import Any

from keel.sdk.naming import camel, identifier, pascal


def php_literal(v: Any, indent: int = 0) -> str:
    pad = "    " * indent
    if isinstance(v, dict):
        if not v:
            return "[]"
        items = [f"{pad}    {php_literal(k)} => {php_literal(x, indent + 1)}," for k, x in v.items()]
        return "[\n" + "\n".join(items) + f"\n{pad}]"
    if isinstance(v, list):
        return "[" + ", ".join(php_literal(x, indent) for x in v) + "]"
    if isinstance(v, bool):
        return "true" if v else "false"
    if v is None:
        return "null"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("\\", "\\\\").replace("'", "\\'") + "'"


class _Types:
    """Collects enum and class definitions; nested objects become `<Parent><Field>` classes."""

    def __init__(self) -> None:
        self.defs: list[str] = []

    def expr(self, schema: dict[str, Any], name: str) -> tuple[str, str, str]:
        """(php type, docblock type, toArray expression template with `$v`)"""
        php, doc, conv = "mixed", "mixed", "$v"
        if "enum" in schema:
            values = [v for v in schema["enum"] if v is not None]
            cases = "\n".join(f"    case {pascal(identifier(str(v)))} = {php_literal(v)};" for v in values)
            self.defs.append(f"enum {name}: string\n{{\n{cases}\n}}\n")
            php, doc, conv, nullable, ty = name, name, "$v->value", None in schema["enum"], "enum"
        else:
            t = schema.get("type")
            if t is None:
                return "mixed", "mixed", "$v"
            types = [x for x in (t if isinstance(t, list) else [t]) if x != "null"]
            nullable = isinstance(t, list) and "null" in t
            ty = types[0] if types else "null"
        if ty == "string":
            php = doc = "string"
        elif ty == "integer":
            php = doc = "int"
        elif ty == "number":
            php = doc = "float"
        elif ty == "boolean":
            php = doc = "bool"
        elif ty == "array":
            inner_php, inner_doc, inner_conv = self.expr(schema.get("items") or {}, name + "Item")
            php, doc = "array", f"list<{inner_doc}>"
            conv = "$v" if inner_conv == "$v" else f"array_map(fn({inner_php} $v) => {inner_conv}, $v)"
        elif ty == "object":
            cls = self.klass(schema, name)
            php = doc = cls
            conv = "$v" if cls == "array" else "$v->toArray()"
        if nullable:
            php, doc = "?" + php, doc + "|null"
            if conv != "$v":
                conv = f"($v === null ? null : {conv})"
        return php, doc, conv

    def klass(self, schema: dict[str, Any], name: str) -> str:
        props = schema.get("properties") or {}
        if not props:
            return "array"
        required = set(schema.get("required") or [])
        ordered = [k for k in props if k in required] + [k for k in props if k not in required]
        params, docs, arr = [], [], []
        for k in ordered:
            php, doc, conv = self.expr(props[k], name + pascal(k))
            optional = k not in required
            if optional and not php.startswith("?") and php != "mixed":
                php = "?" + php
            params.append(f"        public readonly {php} ${k}" + (" = null" if optional else "") + ",")
            docs.append(f"     * @param {doc} ${k}")
            arr.append(f"            {php_literal(k)} => " + conv.replace("$v", f"$this->{k}") + ",")
        self.defs.append(
            f"final class {name}\n{{\n    /**\n" + "\n".join(docs) + "\n     */\n    public function __construct(\n"
            + "\n".join(params) + "\n    ) {\n    }\n\n    /** @return array<string, mixed> */\n    public function toArray(): array\n    {\n        return [\n"
            + "\n".join(arr) + "\n        ];\n    }\n}\n"
        )
        return name


def render(doc: dict[str, Any], **options: Any) -> str:
    name, kinds, relations, events = doc["cartridge"], list(doc["entities"]), list(doc["relations"]), doc["events"]
    namespace = options.get("package") or f"Keel\\{pascal(name)}"
    types = _Types()
    payloads = {t: types.expr(spec["payload"], pascal(t) + "Payload") for t, spec in events.items()}
    lines = [
        "<?php",
        f"// Generated by keel-context from cartridge {name}" + (f" {doc['version']}" if doc.get("version") else "") + ". Do not edit.",
        f"// Regenerate: keel sdk php <path to {name}> -o <this file> --package '{namespace}'",
        "declare(strict_types=1);",
        "",
        f"namespace {namespace};",
        "",
        "use Keel\\Sdk\\Client;",
        "use Keel\\Sdk\\Envelope;",
        "",
        "final class Cartridge",
        "{",
        f"    public const NAME = {php_literal(name)};",
        f"    public const KINDS = {php_literal(kinds)};",
        f"    public const RELATIONS = {php_literal(relations)};",
        f"    public const AGENTS = {php_literal(list(doc['agents']))};",
        "    public const SCOPES = ['global', 'tenant', 'task', 'agent'];",
        f"    public const RULES = {php_literal(doc['rules'], 1)};",
        "}",
        "",
        "final class Subjects",
        "{",
        *[f"    public static function {camel(k)}(string $id): string\n    {{\n        return \"{k}:$id\";\n    }}\n" for k in kinds],
        "}",
        "",
        "// Event payloads (cartridge.yaml `payload:`; extra fields are allowed by the server)",
        "",
        *types.defs,
        "// One constructor per cataloged event: a valid envelope (as an array), typed by payload.",
        "final class Emit",
        "{",
    ]
    for etype in events:
        php, _, conv = payloads[etype]
        payload_expr = conv.replace("$v", "$payload") if php != "array" else "$payload"
        lines += [
            f"    public static function {camel(etype)}(string $tenant, string $subject, \\DateTimeInterface|string $occurredAt, string $source, {php} $payload, ?string $id = null, \\DateTimeInterface|string|null $recordedAt = null): array",
            "    {",
            f"        return Envelope::make({php_literal(etype)}, $tenant, $subject, $occurredAt, $source, {payload_expr}, $id, $recordedAt);",
            "    }",
            "",
        ]
    lines += [
        "}",
        "",
        "final class Keel",
        "{",
        "    /** The five tools over HTTP, bound to one tenant and agent. */",
        "    public static function client(string $baseUrl, string $tenant, ?string $secret = null, ?string $agent = null, int $timeout = 30, ?string $traceparent = null): Client",
        "    {",
        "        return new Client($baseUrl, $tenant, $secret, $agent, $timeout, $traceparent);",
        "    }",
        "}",
        "",
    ]
    return "\n".join(lines)
