"""TypeScript template. Output imports the runtime `@keel-context/sdk` (sdk/typescript in the repo)."""

from __future__ import annotations

import json
import re
from typing import Any


def pascal(name: str) -> str:
    return "".join(p[:1].upper() + p[1:] for p in re.split(r"[._\-\s]+", name) if p)


def camel(name: str) -> str:
    p = pascal(name)
    return p[:1].lower() + p[1:]


def ts_type(schema: dict[str, Any]) -> str:
    """JSON Schema (the §5.5 subset) to a TypeScript type expression."""
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    t = schema.get("type")
    if t is None:
        return "unknown"
    out = []
    for ty in t if isinstance(t, list) else [t]:
        if ty == "null":
            out.append("null")
        elif ty == "string":
            out.append("string")
        elif ty in ("integer", "number"):
            out.append("number")
        elif ty == "boolean":
            out.append("boolean")
        elif ty == "array":
            out.append(f"Array<{ts_type(schema.get('items') or {})}>")
        elif ty == "object":
            out.append(_ts_object(schema))
    return " | ".join(out) or "unknown"


def _ts_object(schema: dict[str, Any]) -> str:
    props = schema.get("properties") or {}
    if not props:
        return "Record<string, unknown>"
    required = set(schema.get("required") or [])
    fields = []
    for name, sub in props.items():
        key = name if re.fullmatch(r"[A-Za-z_$][A-Za-z0-9_$]*", name) else json.dumps(name)
        fields.append(f"{key}{'' if name in required else '?'}: {ts_type(sub)}")
    return "{ " + "; ".join(fields) + " }"


def render(doc: dict[str, Any]) -> str:
    name, kinds, relations = doc["cartridge"], list(doc["entities"]), list(doc["relations"])
    events: dict[str, dict[str, Any]] = doc["events"]
    lines = [
        f"// Generated by keel-context {doc['keel']} from cartridge {name}" + (f" {doc['version']}" if doc.get("version") else "") + ". Do not edit.",
        f"// Regenerate: keel sdk typescript <path to {name}> -o <this file>",
        'import { Client, envelope, type ClientOptions, type Envelope } from "@keel-context/sdk";',
        "",
        f"export const cartridge = {json.dumps(name)} as const;",
        f"export const kinds = {json.dumps(kinds)} as const;",
        "export type Kind = (typeof kinds)[number];",
        "export type Subject<K extends Kind = Kind> = `${K}:${string}`;",
        "export const subjects = {",
        *[f"  {k}: (id: string): Subject<{json.dumps(k)}> => `{k}:${{id}}`," for k in kinds],
        "} as const;",
        f"export const relations = {json.dumps(relations)} as const;",
        "export type Relation = (typeof relations)[number];",
        f"export const rules = {json.dumps(doc['rules'], ensure_ascii=False)} as const;",
        f"export const agents = {json.dumps(list(doc['agents']))} as const;",
        'export const scopes = ["global", "tenant", "task", "agent"] as const;',
        "",
        "// Event payloads (cartridge.yaml `payload:`; extra fields are allowed by the server)",
    ]
    for etype, spec in events.items():
        lines.append(f"export type {pascal(etype)}Payload = {ts_type(spec['payload'])};")
    lines += [
        "",
        "export type EventType = " + (" | ".join(json.dumps(t) for t in events) if events else "never") + ";",
        "export type Payloads = {",
        *[f"  {json.dumps(t)}: {pascal(t)}Payload;" for t in events],
        "};",
        "",
        "export type EmitArgs<T extends EventType, K extends Kind> = {",
        "  tenant: string;",
        "  subject: Subject<K>;",
        "  occurredAt: Date | string;",
        "  source: string;",
        "  payload: Payloads[T];",
        "  id?: string;",
        "  recordedAt?: Date | string;",
        "};",
        "",
        "// One constructor per cataloged event: a valid envelope, typed by subject kind and payload.",
        "export const emit = {",
    ]
    for etype, spec in events.items():
        lines.append(
            f"  {camel(etype)}: (a: EmitArgs<{json.dumps(etype)}, {json.dumps(spec['subject'])}>): Envelope => "
            f"envelope({{ type: {json.dumps(etype)}, ...a }}),"
        )
    lines += [
        "} as const;",
        "",
        "// The five tools, bound to one tenant (and agent) at `baseUrl`; subjects are typed for this cartridge.",
        "export const client = (options: ClientOptions): Client<Subject> => new Client<Subject>(options);",
        "",
    ]
    return "\n".join(lines)
